-- How much revenue is generated by repeat customers, what proportion of total revenue do they contribute, and who is the top-spending customer in each state for potential customer appreciation rewards?

WITH customer_order_table AS (
    WITH order_customer_table AS (
        WITH payment_per_order AS (
            SELECT 
                order_id,
                SUM(payment_value) AS order_payment
            FROM order_payments
            GROUP BY order_id
        )

        SELECT
            p.order_id,
            o.customer_id,
            p.order_payment
        FROM payment_per_order p
        INNER JOIN orders o
            ON p.order_id = o.order_id
    )

    SELECT 
        oc.order_id,
        oc.customer_id,
        c.customer_unique_id,
        c.customer_state,
        oc.order_payment
    FROM order_customer_table oc
    INNER JOIN customers c
        ON oc.customer_id = c.customer_id
),

customer_state_spending AS (
    SELECT
        customer_unique_id,
        customer_state,
        SUM(order_payment) AS amount_spent_by_customer,
        RANK() OVER (
            PARTITION BY customer_state
            ORDER BY SUM(order_payment) DESC
        ) AS spending_rank
    FROM customer_order_table
    GROUP BY customer_unique_id, customer_state
)

SELECT
    customer_state,
    customer_unique_id,
    amount_spent_by_customer,
    spending_rank
FROM customer_state_spending
WHERE spending_rank = 1
ORDER BY customer_state;
